export async function seedEquipmentDatabase(): Promise<{
  success: boolean;
  manufacturersCreated: number;
  equipmentCreated: number;
  errors: string[];
}> {
  const errors: string[] = [];
  let manufacturersCreated = 0;
  let equipmentCreated = 0;

  // Step 1: Insert manufacturers
  const manufacturerIdMap: Record<string, string> = {};

  for (const mfr of manufacturers) {
    const { data, error } = await supabase
      .from("manufacturers")
      .upsert(
        {
          name: mfr.name,
          country: mfr.country,
          website: mfr.website,
          founded_year: mfr.founded_year,
          publicly_traded: mfr.publicly_traded,
          stock_ticker: mfr.stock_ticker ?? null,
          headquarters_city: mfr.headquarters_city,
          employee_count_approx: mfr.employee_count_approx,
          description: mfr.description,
        },
        { onConflict: "name" }
      )
      .select("id, name")
      .single();

    if (error) {
      errors.push(`Manufacturer ${mfr.name}: ${error.message}`);
      continue;
    }

    manufacturerIdMap[mfr.name] = data.id;
    manufacturersCreated++;
  }

  // Step 2: Insert equipment with specs
  for (const eq of equipmentData) {
    const manufacturerId = manufacturerIdMap[eq.manufacturerName];
    if (!manufacturerId) {
      errors.push(`Skipping ${eq.model_name}: manufacturer ${eq.manufacturerName} not found`);
      continue;
    }

    // Insert main equipment record
    const { data: equipmentRecord, error: equipmentError } = await supabase
      .from("equipment")
      .upsert(
        {
          manufacturer_id: manufacturerId,
          product_type: eq.product_type,
          model_name: eq.model_name,
          model_number: eq.model_number ?? null,
          status: eq.status,
          release_year: eq.release_year ?? null,
          description: eq.description,
          certifications: eq.certifications,
          ul_listed: eq.ul_listed ?? null,
          iec_certified: eq.iec_certified ?? null,
          warranty_years: eq.warranty_years ?? null,
          regions_available: eq.regions_available,
          data_source: eq.data_source,
          data_verified: eq.data_verified,
        },
        { onConflict: "manufacturer_id,model_name,model_number" }
      )
      .select("id")
      .single();

    if (equipmentError) {
      errors.push(`Equipment ${eq.model_name}: ${equipmentError.message}`);
      continue;
    }

    // Insert type-specific specs
    const specTable =
      eq.product_type === "BESS"
        ? "bess_specs"
        : eq.product_type === "Solar Panel"
        ? "solar_panel_specs"
        : eq.product_type === "Inverter"
        ? "inverter_specs"
        : "ev_charger_specs";

    const { error: specError } = await supabase.from(specTable).upsert(
      {
        equipment_id: equipmentRecord.id,
        ...eq.specs,
      } as Record<string, unknown>,
      { onConflict: "equipment_id" }
    );

    if (specError) {
      errors.push(`Specs for ${eq.model_name}: ${specError.message}`);
      continue;
    }

    // Create changelog entry
    await supabase.from("equipment_changelog").insert({
      equipment_id: equipmentRecord.id,
      change_type: "created",
      change_reason: "Initial seed from CEO Agent database",
      changed_by: "CEO Agent (seed)",
    });

    equipmentCreated++;
  }

  return {
    success: errors.length === 0,
    manufacturersCreated,
    equipmentCreated,
    errors,
  };
}
